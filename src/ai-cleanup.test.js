function provider() {
  const contents={'README.md':'Generated by Codex\n# Useful product guide\n','src/feature.js':'export const endpoint="https://api.openai.com";\n','package.json':'{"dependencies":{"openai":"1"}}'},source=snapshot(contents),registration=JSON.stringify({id:'grnwht',managed:true,repository:'lrnolivia/gwfamily',default_branch:'main'}),policyBytes=Buffer.from(registration),calls=[];
  const request=async(_env,path,options={})=>{
    calls.push({path,options});assert.equal(options.method,undefined);assert.equal(options.body,undefined);
    if(path==='/repos/lrnolivia/relay/contents/projects/grnwht.json?ref=main')return {type:'file',encoding:'base64',sha:cleanupBlobSha(policyBytes),content:policyBytes.toString('base64')};
    if(path==='/repos/lrnolivia/gwfamily/git/ref/heads/main')return {object:{sha:head}};
    if(path===`/repos/lrnolivia/gwfamily/git/commits/${head}`)return {sha:head,tree:{sha:tree}};
    if(path===`/repos/lrnolivia/gwfamily/git/trees/${tree}?recursive=1`)return {sha:tree,truncated:false,tree:source.files.map(f=>({path:f.path,mode:f.mode,type:'blob',sha:f.blob_sha,size:Buffer.byteLength(f.content)}))};
    const file=source.files.find(f=>path===`/repos/lrnolivia/gwfamily/git/blobs/${f.blob_sha}`);
    if(file)return {sha:file.blob_sha,size:Buffer.byteLength(file.content),encoding:'base64',content:Buffer.from(file.content).toString('base64')};
    throw Error('Unexpected read: '+path);
  };
  return {source,calls,request};
}

test('named MCP handler scans exact registered source and prepares a review patch using GETs only',async()=>{
  const f=provider(),args={action:'scan',project:'grnwht',expected_head_sha:head,paths:f.source.scope},got=await callAiCleanup({},args,f.request);
  assert.equal(aiCleanupTool.name,'relay_ai_cleanup');assert.equal(aiCleanupTool.title,'AI Cleanup');assert.equal(aiCleanupTool.annotations.readOnlyHint,true);
  assert.equal(got.ok,true);assert.equal(got.report.repository,'lrnolivia/gwfamily');
  assert.equal(got.report.findings.filter(x=>x.disposition==='patch_candidate').length,1);
  const selected=got.report.findings.filter(x=>x.disposition==='patch_candidate').map(x=>x.id),prepared=await callAiCleanup({},{...args,action:'prepare_patch',expected_report_sha256:got.report.report_sha256,selected_findings:selected},f.request);
  assert.match(prepared.plan.patch,/-Generated by Codex/);assert.equal(prepared.plan.applied,false);assert.equal(prepared.plan.files.length,1);
  assert.equal(f.calls.filter(c=>c.path.includes('/git/blobs/')).length,4,'protected package contents were never read');
});

test('MCP snapshot refuses a moved head, truncated tree, damaged blob and cross-project policy',async()=>{
  const args={action:'scan',project:'grnwht',expected_head_sha:head,paths:['README.md']};
  for(const alteration of [
    (path,value)=>path.includes('/git/ref/')?{object:{sha:'d'.repeat(40)}}:value,
    (path,value)=>path.includes('/git/trees/')?{...value,truncated:true}:value,
    (path,value)=>path.includes('/git/blobs/')?{...value,content:Buffer.from('wrong').toString('base64')}:value,
    (path,value)=>path.includes('/projects/')?{...value,sha:'d'.repeat(40)}:value
  ]) {const f=provider();await assert.rejects(callAiCleanup({},args,async(env,path,options)=>alteration(path,await f.request(env,path,options))));}
  const f=provider();let reads=0;await assert.rejects(callAiCleanup({},args,async(env,path,options)=>{const value=await f.request(env,path,options);return path.includes('/git/ref/')&&++reads===2?{object:{sha:'d'.repeat(40)}}:value;}),/moved during inventory/);
});

