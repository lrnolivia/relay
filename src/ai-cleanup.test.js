import test from 'node:test';
import assert from 'node:assert/strict';
import {AI_CLEANUP_LIMITS,aiCleanupTool,cleanupBlobSha,scanAiCleanup,prepareAiCleanup,callAiCleanup,validateAiCleanupArguments} from './ai-cleanup.js';
import '../scripts/ai-cleanup.test.mjs';

const head='a'.repeat(40),tree='b'.repeat(40),policy='c'.repeat(40);
function snapshot(contents,extra={}) {
  const files=Object.entries(contents).map(([path,content])=>({path,content,mode:'100644',blob_sha:cleanupBlobSha(Buffer.from(content))}));
  return {schema:1,project:'grnwht',repository:'lrnolivia/gwfamily',branch:'main',head_sha:head,tree_sha:tree,policy_sha:policy,scope:files.map(f=>f.path),complete:true,files,...extra};
}
const plan=(source,report,findings=report.findings.filter(f=>['patch_candidate','migration_proposal'].includes(f.disposition)))=>prepareAiCleanup(source,{expected_report_sha256:report.report_sha256,selected_findings:findings.map(f=>f.id)});

test('proposes only standalone header credits; runtime strings and useful comments remain intact',()=>{
  const source=snapshot({'src/feature.js':'// Generated with Claude Code\n// Useful: the model returns JSON, not plain text.\nexport const model = "claude-opus";\nconst documentation = `\n// Generated by Codex\n`;\n// Generated by ChatGPT\n'}),report=scanAiCleanup(source),result=plan(source,report);
  assert.deepEqual(result.files[0].removed_lines,[1]);
  const after=Buffer.from(result.files[0].after_base64,'base64').toString();
  assert.match(after,/Useful: the model returns JSON/);assert.match(after,/"claude-opus"/);assert.match(after,/Generated by Codex/);assert.match(after,/Generated by ChatGPT/);
  assert.equal(result.applied,false);assert.equal(result.state,'review_required');
});

