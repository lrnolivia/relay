test('reports are deterministic and bind exact scope, bytes, policy and source before explicit selection',()=>{
  const source=snapshot({'README.md':'Generated by Codex\n# Useful guide\n','src/a.js':'export const value=1;\n'}),report=scanAiCleanup(source);
  assert.deepEqual(scanAiCleanup({...source,scope:[...source.scope].reverse(),files:[...source.files].reverse()}),report);
  assert.throws(()=>prepareAiCleanup(source,{expected_report_sha256:report.report_sha256,selected_findings:[]}),/bounded unique/);
  assert.throws(()=>prepareAiCleanup(source,{expected_report_sha256:report.report_sha256,selected_findings:['missing']}),/Unknown/);
  assert.throws(()=>plan({...source,head_sha:'d'.repeat(40)},report),/identity changed/);
  assert.throws(()=>plan({...source,policy_sha:'d'.repeat(40)},report),/identity changed/);
  assert.throws(()=>plan({...source,files:source.files.map(f=>({...f,content:f.content+'drift'}))},report),/Git blob identity/);
});

test('incomplete, oversized, duplicate, unsafe and mismatched snapshots fail closed',()=>{
  const source=snapshot({'README.md':'Generated by Codex\n'});
  for(const next of [{...source,complete:false},{...source,files:[]},{...source,scope:['README.md','README.md']},{...source,repository:'other/repo'}])assert.throws(()=>scanAiCleanup(next));
  for(const path of ['../README.md','/README.md','.git/config','.env','docs/../../LICENSE','a\\b.md'])assert.throws(()=>scanAiCleanup(snapshot({[path]:'Generated by Codex\n'})));
  assert.throws(()=>scanAiCleanup(snapshot({'README.md':'a'.repeat(AI_CLEANUP_LIMITS.file_bytes+1)})),/text window/);
  const total=snapshot({'a.md':'a'.repeat(50000),'b.md':'b'.repeat(50000),'c.md':'c'.repeat(50000)});assert.throws(()=>scanAiCleanup(total),/text window/);
  assert.throws(()=>scanAiCleanup(snapshot({'README.md':'Generated by Codex\n'.repeat(AI_CLEANUP_LIMITS.findings+1)})),/Too many findings/);
});

