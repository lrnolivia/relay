import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// Generate outside Worker compilation. Never serialize a transformed function:
// keepNames and bundler helpers are not available inside the card iframe.
const root=fileURLToPath(new URL('../',import.meta.url));
const target=new URL('../src/relay-context-card-browser.js',import.meta.url);
const result=await build({absWorkingDir:root,entryPoints:['src/relay-context-card-model.js'],
  bundle:true,write:false,format:'iife',globalName:'RelayContextCard',platform:'browser',
  target:'es2022',minify:true,keepNames:false});
const model='(()=>{'+result.outputFiles[0].text+';return RelayContextCard.contextCardModel})()';
const content='// Generated by scripts/build-context-card-model.mjs. Do not hand edit.\n'+
  'export const CONTEXT_CARD_BROWSER_MODEL = '+JSON.stringify(model)+';\n';
if(process.argv[2]==='--check'){
  if(await readFile(target,'utf8')!==content)throw Error('Context-card browser model is stale; run node scripts/build-context-card-model.mjs');
}else if(process.argv.length===2)await writeFile(target,content);
else throw Error('Use no argument to generate, or --check to verify');
